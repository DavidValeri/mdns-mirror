"""Check that every spec story and ADR is covered by a test or a manual check.

Tests declare what they verify with @pytest.mark.covers("story:17", "adr:0004").
Requirements that are checked by hand are listed in MANUAL below, with a reason.

Running this script also regenerates docs/testing.md from the same data.

Exits non-zero if a requirement has no test and no manual entry, a test names
an unknown requirement, or a manual entry is stale.
"""

import pathlib
import re
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPORT = ROOT / "docs" / "testing.md"

MANUAL = {
    "story:1": "Container packaging and VM setup are done by hand. See deploy/vm-setup.md.",
    "story:2": "Management IP is set during VM setup. Check with the steps in deploy/vm-setup.md.",
    "story:3": "No IP on mirrored networks is set during VM setup. Check with the steps in deploy/vm-setup.md.",
    "story:4": "Forwarding is turned off during VM setup. Check with the steps in deploy/vm-setup.md.",
    "story:5": "Per-network macvlan attachment is set during VM setup. Check with deploy/vm-setup.md.",
    "story:6": "Management-network address is set during VM setup. Check with deploy/vm-setup.md.",
    "story:30": "Restart behavior comes from the Compose restart policy. Check by restarting the container after setup.",
    "story:31": "Start on boot comes from Docker starting on boot. Check by rebooting the VM after setup.",
    "story:32": "Reproducibility is the guide itself. Check by following deploy/vm-setup.md on a fresh VM.",
    "story:33": "VLAN mapping is checked by deploy/check-vlans.sh before the container starts.",
    "story:34": "A missing VLAN is reported by deploy/check-vlans.sh before the container starts.",
    "story:35": "Design review, not a test.",
    "story:36": "Design property, not a test.",
    "adr:0005": "CI release decision, not a pytest test. Verified in the release workflow run: the test and promote steps must show the same candidate digest, and the shipped image must start without test tools.",
}


def requirements():
    """Read the story and ADR IDs and titles from the spec and ADR folder."""
    found = {}
    spec = (ROOT / ".scratch" / "mdns-mirror" / "spec.md").read_text()
    for number, text in re.findall(r"^(\d+)\. (As an? .+)$", spec, re.MULTILINE):
        found[f"story:{int(number)}"] = text if len(text) <= 100 else text[:97] + "..."
    for path in sorted((ROOT / "docs" / "adr").glob("*.md")):
        number = path.name.split("-")[0]
        found[f"adr:{number}"] = path.read_text().splitlines()[0].removeprefix("# ")
    return found


class _Collector:
    """Pytest plugin that records which tests declare each requirement."""

    def __init__(self):
        self.tests = {}

    def pytest_collection_finish(self, session):
        for item in session.items:
            name = f"{pathlib.Path(item.path).relative_to(ROOT)}::{item.originalname}"
            for marker in item.iter_markers("covers"):
                for ident in marker.args:
                    self.tests.setdefault(ident, set()).add(name)


def collected_tests():
    """Collect every test and the requirements it declares."""
    collector = _Collector()
    pytest.main(["--collect-only", "-p", "no:cacheprovider", "-p", "no:terminal", str(ROOT / "tests")], plugins=[collector])
    return collector.tests


def _sort_key(ident):
    kind, number = ident.split(":")
    return (kind, int(number))


def render(reqs, covered):
    """Build the markdown report."""
    lines = [
        "# Test coverage",
        "",
        "Generated by `scripts/check_coverage.py` from the `covers` markers in `tests/` "
        "and the manual list in that script. Do not edit by hand.",
        "",
        "| Requirement | Title | Status | Tests or manual check |",
        "| --- | --- | --- | --- |",
    ]
    for ident in sorted(reqs, key=_sort_key):
        if ident in covered:
            status = "Automated"
            detail = "<br>".join(f"`{name}`" for name in sorted(covered[ident]))
        else:
            status = "Manual"
            detail = MANUAL.get(ident, "")
        lines.append(f"| {ident} | {reqs[ident]} | {status} | {detail} |")
    return "\n".join(lines) + "\n"


def main():
    """Run the check, regenerate the report, and report any problems."""
    reqs = requirements()
    covered = collected_tests()
    problems = []
    for ident in sorted(covered, key=_sort_key):
        if ident not in reqs:
            problems.append(f"test marks unknown requirement {ident}: {sorted(covered[ident])}")
    for ident in sorted(MANUAL, key=_sort_key):
        if ident not in reqs:
            problems.append(f"manual entry for unknown requirement {ident}")
        elif ident in covered:
            problems.append(f"{ident} has both a manual entry and automated tests; remove one")
    for ident in sorted(reqs, key=_sort_key):
        if ident not in covered and ident not in MANUAL:
            problems.append(f"{ident} has no test or manual entry: {reqs[ident]}")
    REPORT.write_text(render(reqs, covered))
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
